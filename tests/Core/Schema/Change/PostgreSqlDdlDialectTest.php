<?php

declare(strict_types=1);

namespace App\Tests\Core\Schema\Change;

use App\Core\Schema\Change\ColumnDraft;
use App\Core\Schema\Change\Dialect\PostgreSqlDdlDialect;
use App\Core\Schema\Change\Exception\InvalidSchemaChangeException;
use App\Core\Schema\Change\ForeignKeyDraft;
use App\Core\Schema\Change\IndexDraft;
use App\Core\Schema\Change\Operation\AddColumn;
use App\Core\Schema\Change\Operation\AddForeignKey;
use App\Core\Schema\Change\Operation\AddIndex;
use App\Core\Schema\Change\Operation\DropColumn;
use App\Core\Schema\Change\Operation\DropForeignKey;
use App\Core\Schema\Change\Operation\DropIndex;
use App\Core\Schema\Change\Operation\DropTable;
use App\Core\Schema\Change\Operation\ModifyColumn;
use App\Core\Schema\Change\Operation\RenameColumn;
use App\Core\Schema\Change\Operation\RenameIndex;
use App\Core\Schema\Change\Operation\RenameTable;
use App\Core\Schema\Change\Operation\SetPrimaryKey;
use App\Core\Schema\ColumnDefinition;
use App\Core\Schema\IndexDefinition;
use App\Core\Schema\ReferentialAction;
use PHPUnit\Framework\TestCase;

final class PostgreSqlDdlDialectTest extends TestCase
{
    /**
     * @param list<object> $operations
     *
     * @return list<string>
     */
    private static function sql(array $operations): array
    {
        return array_map(static fn ($statement): string => $statement->sql, (new PostgreSqlDdlDialect())->statements('orders', $operations));
    }

    public function testQuotesNamesAndDoublesTheQuotesInside(): void
    {
        self::assertSame(['ALTER TABLE "orders" ADD COLUMN "we""ird" text'], self::sql([new AddColumn(new ColumnDraft(null, 'we"ird', 'text', true, null, false))]));
    }

    public function testAddsAColumnWithItsConstraintsAndDefault(): void
    {
        self::assertSame(
            ['ALTER TABLE "orders" ADD COLUMN "status" character varying(20) NOT NULL DEFAULT \'new\''],
            self::sql([new AddColumn(new ColumnDraft(null, 'status', 'character varying(20)', false, 'new', false))]),
        );
        self::assertSame(
            ['ALTER TABLE "orders" ADD COLUMN "created_at" timestamp NOT NULL DEFAULT now()'],
            self::sql([new AddColumn(new ColumnDraft(null, 'created_at', 'timestamp', false, 'now()', false))]),
        );
    }

    public function testAnAutoIncrementColumnBecomesAnIdentityAndIgnoresItsDefault(): void
    {
        self::assertSame(
            ['ALTER TABLE "orders" ADD COLUMN "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL'],
            self::sql([new AddColumn(new ColumnDraft(null, 'id', 'integer', false, '5', true))]),
        );
    }

    public function testEscapesAStringDefaultAndNeverLetsItBreakOut(): void
    {
        self::assertSame(
            ['ALTER TABLE "orders" ADD COLUMN "n" text DEFAULT \'x\'\'; DROP TABLE users; --\''],
            self::sql([new AddColumn(new ColumnDraft(null, 'n', 'text', true, "x'; DROP TABLE users; --", false))]),
        );
    }

    public function testDropsAndRenamesColumns(): void
    {
        self::assertSame(['ALTER TABLE "orders" DROP COLUMN "note"'], self::sql([new DropColumn('note')]));
        self::assertSame(['ALTER TABLE "orders" RENAME COLUMN "a" TO "b"'], self::sql([new RenameColumn('a', 'b')]));
    }

    public function testModifiesTypeNullabilityAndDefaultInOneStatement(): void
    {
        $before = new ColumnDefinition('status', 'varchar(20)', false, "'new'::character varying", false, null);
        $after = new ColumnDraft('status', 'status', 'varchar(40)', true, null, false);

        self::assertSame(
            ['ALTER TABLE "orders" ALTER COLUMN "status" TYPE varchar(40) USING "status"::varchar(40), ALTER COLUMN "status" DROP NOT NULL, ALTER COLUMN "status" DROP DEFAULT'],
            self::sql([new ModifyColumn($before, $after, true, true, true, false)]),
        );
    }

    public function testSetsADefaultAndNotNull(): void
    {
        $before = new ColumnDefinition('n', 'integer', true, null, false, null);
        $after = new ColumnDraft('n', 'n', 'integer', false, '0', false);

        self::assertSame(
            ['ALTER TABLE "orders" ALTER COLUMN "n" SET NOT NULL, ALTER COLUMN "n" SET DEFAULT 0'],
            self::sql([new ModifyColumn($before, $after, false, true, true, false)]),
        );
    }

    public function testTurnsAColumnIntoAnIdentityAndBack(): void
    {
        $plain = new ColumnDefinition('id', 'integer', false, null, false, null);
        $serial = new ColumnDefinition('id', 'integer', false, "nextval('orders_id_seq'::regclass)", true, null);

        self::assertSame(
            ['ALTER TABLE "orders" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY'],
            self::sql([new ModifyColumn($plain, new ColumnDraft('id', 'id', 'integer', false, null, true), false, false, false, true)]),
        );
        self::assertSame(
            ['ALTER TABLE "orders" ALTER COLUMN "id" DROP IDENTITY IF EXISTS, ALTER COLUMN "id" DROP DEFAULT'],
            self::sql([new ModifyColumn($serial, new ColumnDraft('id', 'id', 'integer', false, null, false), false, false, true, true)]),
        );
    }

    public function testPrimaryKey(): void
    {
        $old = new IndexDefinition('orders_pkey', ['id'], true, true);

        self::assertSame(
            ['ALTER TABLE "orders" DROP CONSTRAINT "orders_pkey"', 'ALTER TABLE "orders" ADD PRIMARY KEY ("id", "customer_id")'],
            self::sql([new SetPrimaryKey($old, new IndexDraft(null, 'PRIMARY', ['id', 'customer_id'], true, true, null, null))]),
        );
        self::assertSame(['ALTER TABLE "orders" DROP CONSTRAINT "orders_pkey"'], self::sql([new SetPrimaryKey($old, null)]));
    }

    public function testIndexes(): void
    {
        self::assertSame(['CREATE INDEX "idx_s" ON "orders" ("status")'], self::sql([new AddIndex(new IndexDraft(null, 'idx_s', ['status'], false, false, null, null))]));
        self::assertSame(['CREATE UNIQUE INDEX "u" ON "orders" ("a", "b")'], self::sql([new AddIndex(new IndexDraft(null, 'u', ['a', 'b'], true, false, null, null))]));
        self::assertSame(['DROP INDEX "idx_s"'], self::sql([new DropIndex('idx_s', new IndexDefinition('idx_s', ['status'], false, false))]));
        self::assertSame(['ALTER INDEX "a" RENAME TO "b"'], self::sql([new RenameIndex('a', 'b')]));
    }

    public function testDroppingAUniqueIndexAlsoTriesTheConstraintThatMayOwnIt(): void
    {
        self::assertSame(
            ['ALTER TABLE "orders" DROP CONSTRAINT IF EXISTS "u"', 'DROP INDEX IF EXISTS "u"'],
            self::sql([new DropIndex('u', new IndexDefinition('u', ['a'], true, false))]),
        );
    }

    public function testForeignKeys(): void
    {
        $fk = new ForeignKeyDraft(null, 'fk_c', ['customer_id'], 'customers', ['id'], ReferentialAction::NoAction, ReferentialAction::SetNull);

        self::assertSame(
            ['ALTER TABLE "orders" ADD CONSTRAINT "fk_c" FOREIGN KEY ("customer_id") REFERENCES "customers" ("id") ON UPDATE NO ACTION ON DELETE SET NULL'],
            self::sql([new AddForeignKey($fk)]),
        );
        self::assertSame(['ALTER TABLE "orders" DROP CONSTRAINT "fk_c"'], self::sql([new DropForeignKey('fk_c')]));
    }

    public function testRenamesAndDropsTheTable(): void
    {
        self::assertSame(['ALTER TABLE "orders" RENAME TO "sales"'], self::sql([new RenameTable('orders', 'sales')]));
        self::assertSame(['DROP TABLE "orders"'], self::sql([new DropTable('orders')]));
    }

    public function testEmitsStatementsInAnOrderThatNeverBreaksADependency(): void
    {
        $sql = self::sql([
            new AddForeignKey(new ForeignKeyDraft(null, 'fk', ['b'], 't', ['id'], ReferentialAction::NoAction, ReferentialAction::NoAction)),
            new AddIndex(new IndexDraft(null, 'i', ['b'], false, false, null, null)),
            new AddColumn(new ColumnDraft(null, 'b', 'integer', true, null, false)),
            new DropColumn('a'),
            new DropIndex('old', new IndexDefinition('old', ['a'], false, false)),
            new DropForeignKey('oldfk'),
            new RenameTable('orders', 'sales'),
        ]);

        self::assertSame([
            'ALTER TABLE "orders" DROP CONSTRAINT "oldfk"',
            'DROP INDEX "old"',
            'ALTER TABLE "orders" DROP COLUMN "a"',
            'ALTER TABLE "orders" ADD COLUMN "b" integer',
            'CREATE INDEX "i" ON "orders" ("b")',
            'ALTER TABLE "orders" ADD CONSTRAINT "fk" FOREIGN KEY ("b") REFERENCES "t" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION',
            'ALTER TABLE "orders" RENAME TO "sales"',
        ], $sql);
    }

    public function testFlagsWhatDestroysDataAndNothingElse(): void
    {
        $statements = (new PostgreSqlDdlDialect())->statements('orders', [
            new DropColumn('a'),
            new RenameColumn('b', 'c'),
            new AddColumn(new ColumnDraft(null, 'd', 'text', true, null, false)),
            new DropTable('orders'),
            new ModifyColumn(new ColumnDefinition('e', 'integer', false, null, false, null), new ColumnDraft('e', 'e', 'bigint', false, null, false), true, false, false, false),
            new ModifyColumn(new ColumnDefinition('f', 'integer', false, null, false, null), new ColumnDraft('f', 'f', 'integer', true, null, false), false, true, false, false),
        ]);

        $flags = [];
        foreach ($statements as $statement) {
            $flags[$statement->operation.':'.$statement->subject] = $statement->destructive;
        }
        self::assertSame(['drop_column:a' => true, 'rename_column:b' => false, 'add_column:d' => false, 'drop_table:orders' => true, 'modify_column:e' => true, 'modify_column:f' => false], [
            'drop_column:a' => $flags['drop_column:a'], 'rename_column:b' => $flags['rename_column:b'], 'add_column:d' => $flags['add_column:d'],
            'drop_table:orders' => $flags['drop_table:orders'], 'modify_column:e' => $flags['modify_column:e'], 'modify_column:f' => $flags['modify_column:f'],
        ]);
    }

    public function testRefusesAnUnsupportedType(): void
    {
        $this->expectException(InvalidSchemaChangeException::class);

        new ColumnDraft(null, 'x', 'int; DROP TABLE y', true, null, false);
    }

    public function testRunsInOneTransaction(): void
    {
        self::assertTrue((new PostgreSqlDdlDialect())->transactional());
    }
}
